"""
Sales & Revenue Drivers Analytics Page.
Renders contribution analysis (what drives revenue), Pareto customer concentration,
top products by revenue and quantity, geographic breakdown, order value distribution,
and hourly/weekday heatmaps.
"""

import streamlit as st
import plotly.express as px
import plotly.graph_objects as go
import pandas as pd

from src.sales_analytics import (
    top_products,
    top_countries_by_revenue,
    compute_order_values,
    compute_pareto_concentration,
    compute_weekday_hourly_distribution,
    what_drives_revenue_analysis,
)


def render(sales_df: pd.DataFrame, customer_df: pd.DataFrame, guest_metrics: dict) -> None:
    st.title("📈 Sales & Revenue Drivers")
    st.caption("Detailed revenue driver decomposition, concentration curves, and demand patterns.")

    if sales_df.empty:
        st.warning("No transaction records match the active filter criteria.")
        return

    # 1. What Drives Revenue Contribution Section
    st.subheader("🎯 What Drives Revenue?")
    drivers = what_drives_revenue_analysis(sales_df)

    c1, c2, c3 = st.columns(3)
    c1.metric(
        "Top 10 Products Share",
        f"{drivers['top_10_product_share']:.1f}%",
        help="Percentage of total sales value generated by the top 10 products.",
    )
    c2.metric(
        f"Primary Country ({drivers['top_country']})",
        f"{drivers['top_country_share']:.1f}%",
        help="Revenue concentration from the single largest geographic market.",
    )
    c3.metric(
        f"MoM Change ({drivers['latest_month']})",
        f"${drivers['mom_delta']:,.2f}",
        delta=f"{drivers['mom_pct_change']:+.1f}%",
        help="Net change in monthly positive sales compared to previous month.",
    )

    if drivers["growing_products"] or drivers["declining_products"]:
        col_grow, col_drop = st.columns(2)
        with col_grow:
            st.markdown("**Top MoM Expanding Products**")
            for item in drivers["growing_products"]:
                st.markdown(f"🟢 **{item['product']}**: +${item['delta']:,.2f}")
        with col_drop:
            st.markdown("**Top MoM Contracting Products**")
            for item in drivers["declining_products"]:
                st.markdown(f"🔴 **{item['product']}**: -${abs(item['delta']):,.2f}")

    st.markdown("---")

    # 2. Pareto Customer Concentration & Order Value Distribution
    col_pareto, col_dist = st.columns(2)

    with col_pareto:
        st.subheader("Customer Revenue Concentration (Pareto)")
        pareto_df, top_20_share = compute_pareto_concentration(customer_df)
        if not pareto_df.empty:
            fig_pareto = go.Figure()
            fig_pareto.add_trace(go.Scatter(
                x=pareto_df["CustomerPercentile"],
                y=pareto_df["CumulativeSharePct"],
                mode="lines",
                name="Cumulative Revenue %",
                line=dict(color="#10B981", width=3),
            ))
            # 80/20 reference lines
            fig_pareto.add_vline(x=20, line_dash="dash", line_color="#F59E0B", annotation_text="Top 20% Customers")
            fig_pareto.add_hline(y=top_20_share, line_dash="dash", line_color="#F59E0B", annotation_text=f"{top_20_share:.1f}% Revenue")
            fig_pareto.update_layout(
                title=f"Pareto Curve: Top 20% generate {top_20_share:.1f}% of identified sales",
                xaxis_title="Cumulative % of Customers",
                yaxis_title="Cumulative % of Sales Value",
                template="plotly_dark",
                margin=dict(l=20, r=20, t=40, b=20),
            )
            st.plotly_chart(fig_pareto, use_container_width=True)
        else:
            st.info("Insufficient customer data for Pareto calculation.")

    with col_dist:
        st.subheader("Order Value Distribution")
        order_values = compute_order_values(sales_df)
        if not order_values.empty:
            # Clip high outliers for visualization readability
            q99 = float(order_values.quantile(0.99))
            clipped = order_values[order_values <= q99]
            fig_hist = px.histogram(
                clipped,
                nbins=40,
                labels={"value": "Order Value ($)"},
                title="Order Value Distribution (Up to 99th Percentile)",
            )
            fig_hist.update_traces(marker_color="#8B5CF6")
            fig_hist.update_layout(
                yaxis_title="Order Count",
                template="plotly_dark",
                margin=dict(l=20, r=20, t=40, b=20),
            )
            st.plotly_chart(fig_hist, use_container_width=True)
        else:
            st.info("No order values available.")

    st.markdown("---")

    # 3. Product Catalog Performance (Revenue vs Quantity)
    col_p1, col_p2 = st.columns(2)

    with col_p1:
        st.subheader("Top 10 Products by Revenue")
        top_rev = top_products(sales_df, by="LineRevenue", top_n=10)
        fig_p_rev = px.bar(
            top_rev.sort_values("Value"),
            x="Value",
            y="Description",
            orientation="h",
            labels={"Value": "Sales Value ($)", "Description": "Product"},
            title="Top Products by Sales Value",
        )
        fig_p_rev.update_traces(marker_color="#EC4899")
        fig_p_rev.update_layout(template="plotly_dark", margin=dict(l=20, r=20, t=40, b=20))
        st.plotly_chart(fig_p_rev, use_container_width=True)

    with col_p2:
        st.subheader("Top 10 Products by Quantity Sold")
        top_qty = top_products(sales_df, by="Quantity", top_n=10)
        fig_p_qty = px.bar(
            top_qty.sort_values("Value"),
            x="Value",
            y="Description",
            orientation="h",
            labels={"Value": "Units Sold", "Description": "Product"},
            title="Top Products by Quantity Sold",
        )
        fig_p_qty.update_traces(marker_color="#3B82F6")
        fig_p_qty.update_layout(template="plotly_dark", margin=dict(l=20, r=20, t=40, b=20))
        st.plotly_chart(fig_p_qty, use_container_width=True)

    st.markdown("---")

    # 4. Geographic Breakdown & Weekday/Hourly Heatmap
    col_geo, col_heat = st.columns(2)

    with col_geo:
        st.subheader("Sales by Country")
        countries = top_countries_by_revenue(sales_df, top_n=10)
        fig_geo = px.bar(
            countries.sort_values("PositiveSales"),
            x="PositiveSales",
            y="Country",
            orientation="h",
            labels={"PositiveSales": "Sales Value ($)", "Country": "Country"},
            title="Top 10 Countries by Sales Value",
        )
        fig_geo.update_traces(marker_color="#14B8A6")
        fig_geo.update_layout(template="plotly_dark", margin=dict(l=20, r=20, t=40, b=20))
        st.plotly_chart(fig_geo, use_container_width=True)

    with col_heat:
        st.subheader("Sales Timing Patterns (Heatmap)")
        heatmap_data = compute_weekday_hourly_distribution(sales_df)
        if not heatmap_data.empty:
            fig_heat = px.imshow(
                heatmap_data,
                labels=dict(x="Hour of Day", y="Day of Week", color="Sales ($)"),
                title="Sales Intensity by Day & Hour",
                color_continuous_scale="Viridis",
            )
            fig_heat.update_layout(template="plotly_dark", margin=dict(l=20, r=20, t=40, b=20))
            st.plotly_chart(fig_heat, use_container_width=True)
        else:
            st.info("Insufficient timestamp data for heatmap.")
